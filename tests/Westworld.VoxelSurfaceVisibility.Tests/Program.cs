using Westworld.Runtime.Core;
using Westworld.Scapi.Adapter;
int n=0;void Check(bool b,string why){if(!b)throw new Exception(why);n++;}
var eye=new Position(.5,66.55,.5);var center=new Position(3.5,64.5,.5);var top=VoxelSurfaceVisibility.SupportTop(3,64,0);var forward=new Position(3,-1.551,0);
bool? Floor(int x,int y,int z)=>y<=64;
Check(!VoxelSurfaceVisibility.LineOfSight(eye,center,Floor),"near floor occludes center");
Check(VoxelSurfaceVisibility.LineOfSight(eye,top,Floor),"visible top not occluded by near floor");
Check(VoxelSurfaceVisibility.InView(eye,forward,top,3,64,0),"downward top inside view");
var samples=VoxelSurfaceVisibility.Samples(eye,3,64,0);
Check(samples.Contains(top),"eye above sees top sample");
Check(samples.All(s=>VoxelSurfaceVisibility.InVoxel(s,3,64,0)),"all samples remain target voxel");
Check(samples.All(s=>s.Y>64.0011&&s.X<3.9989),"no bottom/backface from above left");
bool? Wall(int x,int y,int z)=>x==2||y<=64;
Check(samples.All(s=>!VoxelSurfaceVisibility.LineOfSight(eye,s,Wall)),"wall blocks every sample");
Check(!VoxelSurfaceVisibility.LineOfSight(eye,top,(x,y,z)=>x==2?null:Floor(x,y,z)),"unloaded intermediate remains unknown");
Check(!VoxelSurfaceVisibility.InView(eye,new(-1,0,0),top,3,64,0),"backwards FOV refused");
Check(!VoxelSurfaceVisibility.InView(eye,new(0,0,0),top,3,64,0),"zero forward refused");
Check(!VoxelSurfaceVisibility.InView(new(.5,64.5,.5),new(1,0,0),new(5.501,64.5,.5),5,64,0),"sample outside5 refused");
Check(!VoxelSurfaceVisibility.InView(new(.4,64.5,.5),new(1,0,0),new(5.001,64.5,.5),5,64,0),"near face cannot expand center range");
Check(VoxelSurfaceVisibility.InView(new(.5,64.5,.5),new(1,0,0),new(5.5,64.5,.5),5,64,0),"exact5 center accepted");
Check(!VoxelSurfaceVisibility.InView(eye,forward,new(3.5,65,.5),3,64,0),"boundary air endpoint cannot prove below voxel");
Check(!VoxelSurfaceVisibility.InView(eye,forward,new(double.NaN,64.9,.5),3,64,0),"nan refused");
Check(!VoxelSurfaceVisibility.LineOfSight(eye,new(100,64,.5),Floor),"distance bounded");
Check(!VoxelSurfaceVisibility.LineOfSight(eye,top,(x,y,z)=>null),"unknown first voxel refused");
int targetReads=0;Check(VoxelSurfaceVisibility.LineOfSight(eye,top,(x,y,z)=>{if(x==3&&y==64&&z==0)targetReads++;return y<=64;}),"opaque target face can be seen");Check(targetReads==0,"LOS does not read hidden target before arrival");
var low=new Position(.5,65.2,.5);Check(VoxelSurfaceVisibility.LineOfSight(low,top,Floor),"low eye still sees flat top");
Check(!VoxelSurfaceVisibility.LineOfSight(new(.5,64.5,.5),new(2.5,64.5,2.5),(x,y,z)=>x==0&&y==64&&z==1),"corner touching opaque blocks");
Check(!VoxelSurfaceVisibility.LineOfSight(new(.5,64.5,.5),new(2.5,64.5,2.5),(x,y,z)=>x==0&&y==64&&z==1?null:false),"corner touching unknown blocks");
Console.WriteLine($"PASS {n}/{n} visibility geometry checks; no native sensor/game execution");
