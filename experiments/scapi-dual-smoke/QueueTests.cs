using ScapiDualSmoke;
int checks=0;
void Check(bool value,string name){checks++;if(!value)throw new Exception(name);}
var session=Guid.NewGuid();
ActionRequest Move(int player,long id,double issue=0,double expiry=2,double duration=.4)=>new(session,player,id,ActionKind.Move,issue,expiry,duration,new(0,0,.25f));
ActionRequest Stop(int player,long id,double issue=.1,double expiry=2)=>new(session,player,id,ActionKind.Stop,issue,expiry,0,default);
var q=new ActionQueue(session,[1,2]);
Check(q.Submit(Move(1,1),0),"submit first");
Check(!q.Submit(Move(1,1),0),"pending replay");
Check(!q.Submit(Move(1,2),0),"per-player busy");
Check(q.Submit(Move(2,1),0),"independent second player");
var t=q.Tick(0);
Check(t.Intents[1].Z==.25f && t.Intents[2].Z==.25f,"both move");
Check(t.Events.Count(e=>e.Status=="accepted")==2,"accept events");
Check(q.Tick(.399).Intents[1].Z==.25f,"before duration");
Check(q.Tick(.4).Intents.Values.All(v=>v==default),"duration boundary stops");
Check(!q.Submit(Move(1,1,.4),.4),"completed replay");
Check(q.Submit(Move(1,2,.4),.4),"new id after completion");
q.Tick(.4);
Check(q.Submit(Stop(1,3,.5),.5),"stop active");
t=q.Tick(.5);
Check(t.Intents[1]==default && t.Events.Any(e=>e.RequestId==2&&e.Reason=="stopped"),"stop event and zero");
Check(!q.Submit(Move(1,2,.5),.5),"stop preserves id watermark");
var p=new ActionQueue(session,[1]);
Check(p.Submit(Move(1,1),0)&&p.Submit(Stop(1,2,0),0),"stop pending without backlog");
Check(p.Tick(0).Intents[1]==default,"pending never runs");
var deadline=new ActionQueue(session,[1]);
deadline.Submit(Move(1,1,0,.2),0);
Check(deadline.Tick(.2).Events.Any(e=>e.Reason=="expired_before_start"),"expired queue");
deadline.Submit(Move(1,2,.2,.3),.2); deadline.Tick(.2);
Check(deadline.Tick(.3).Intents[1]==default,"active capped by expiry");
var bad=new ActionQueue(session,[1]);
Check(!bad.Submit(Move(1,1) with {Session=Guid.NewGuid()},0),"wrong session");
Check(!bad.Submit(Move(3,1),0),"unknown player");
Check(!bad.Submit(Move(1,0),0),"nonpositive id");
Check(!bad.Submit(Move(1,1) with {Move=new(float.NaN,0,0)},0),"NaN move");
Check(!bad.Submit(Move(1,1) with {Move=new(1,0,1)},0),"oversized vector");
Check(!bad.Submit(Move(1,1,duration:.401),0),"duration bound");
Check(!bad.Submit(Move(1,1,duration:double.NaN),0),"NaN duration");
Check(!bad.Submit(Move(1,1,issue:1),0),"future issue");
Check(!bad.Submit(Move(1,1,expiry:0),0),"expired submit");
Check(!bad.Submit(Move(1,1),double.NaN),"NaN wall");
Check(!bad.Submit(Move(1,1) with {Kind=(ActionKind)99},0),"invalid enum");
Check(!bad.Submit(Stop(1,1,0) with {Move=new(0,0,1)},0),"invalid stop payload");
Check(bad.Submit(Move(1,1),0),"rejection does not reserve id");
bad.Tick(.1);
Check(bad.Tick(.05).Intents[1]==default,"clock rewind clears intent");
Check(bad.Submit(Move(1,2,.1),.1),"valid request after clock fault");
bad.Tick(.1);
Check(bad.Tick(double.NaN).Intents[1]==default,"NaN tick fails closed");
var concurrent=new ActionQueue(session,[1,2]);int accepted=0;
Parallel.For(0,100,_=>{if(concurrent.Submit(Move(1,1),0))Interlocked.Increment(ref accepted);});
Check(accepted==1,"concurrent duplicate exactly once");
Check(concurrent.Submit(Move(2,1),0),"concurrent busy isolated");
Check(concurrent.Submit(Stop(1,2,0),0),"priority stop after duplicate burst");
t=concurrent.Tick(0);
Check(t.Intents[1]==default&&t.Intents[2].Z==.25f,"stop one leaves other moving");
var raced=new ActionQueue(session,[1]);
raced.Tick(1);
Check(raced.Submit(Move(1,1,.9,2),.99),"producer sampled clock before Tick won lock");
Check(raced.Tick(1.1).Intents[1].Z==.25f,"delayed producer request starts normally");
var expiredRace=new ActionQueue(session,[1]);
expiredRace.Tick(1);
Check(!expiredRace.Submit(Move(1,1,.9,1),.99),"older producer time cannot revive expiry at last Tick");
Check(!expiredRace.Submit(Move(1,1,.9,.999),.99),"older producer time cannot revive expiry before last Tick");
Check(expiredRace.Tick(1.1).Intents[1]==default,"expired racing request never moves");
Console.WriteLine($"{checks}/{checks} queue checks passed");
